/**
 * Replaces all elements with [data-lucide] with inline SVG icons.
 */
export function initIcons() {
  const nodes = document.querySelectorAll('[data-lucide]');
  nodes.forEach((node) => {
    const iconName = node.getAttribute('data-lucide');
    const paths = LUCIDE_ICONS[iconName] || LUCIDE_ICONS.box;
    const isArrow = iconName.includes('arrow') || iconName.includes('chevron');
    const extraClass = isArrow ? ' icon-arrow' : '';
    const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
    svg.setAttribute('viewBox', '0 0 24 24');
    svg.setAttribute('width', node.getAttribute('width') || '22');
    svg.setAttribute('height', node.getAttribute('height') || '22');
    svg.setAttribute('fill', 'none');
    svg.setAttribute('stroke', 'currentColor');
    svg.setAttribute('stroke-width', '2');
    svg.setAttribute('stroke-linecap', 'round');
    svg.setAttribute('stroke-linejoin', 'round');
    svg.setAttribute('aria-hidden', 'true');
    svg.setAttribute('class', `lucide-icon lucide-${iconName}${extraClass}`);
    svg.innerHTML = paths;
    node.replaceWith(svg);
  });
}

